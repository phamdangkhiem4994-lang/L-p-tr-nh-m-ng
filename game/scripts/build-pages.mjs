import {readFile,writeFile} from 'node:fs/promises';
const source=new URL('../public/index.html',import.meta.url);
const target=new URL('../../index.html',import.meta.url);
let html=(await readFile(source,'utf8')).replace(/\r\n/g,'\n');
html=html.replace('<head>','<head>\n  <!-- Generated by game/scripts/build-pages.mjs; edit game/public/index.html. -->\n  <meta name="game-api-origin" content="https://truyen-net.onrender.com">');
html=html.replace('href="/style.css"','href="./game/public/style.css"').replace('src="/client/app.js"','src="./game/client/app.js"').replace('class="wordmark" href="/"','class="wordmark" href="./"');
await writeFile(target,html);
